def validate_static_graph() -> None:
    disease_ids = {x["node_id"] for x in DISEASE_NODES}
    need_ids = {x["node_id"] for x in CONSULTATION_NEED_NODES}
    warning_ids = {x["node_id"] for x in WARNING_NODES}

    assert len(DISEASE_NODES) == 30
    assert len(disease_ids) == 30
    assert len(CONSULTATION_NEED_NODES) == 4
    assert len(need_ids) == 4
    assert len(WARNING_NODES) == 3
    assert len(warning_ids) == 3

    for edge in DISEASE_NEED_EDGES:
        assert edge["source_node_id"] in disease_ids
        assert edge["target_node_id"] in need_ids

    for edge in DISEASE_WARNING_EDGES:
        assert edge["source_node_id"] in disease_ids
        assert edge["target_node_id"] in warning_ids


def upsert_knowledge_graph() -> dict[str, int]:
    validate_static_graph()

    driver = Neo4jClient.get_driver()
    database = Neo4jClient.database_name

    with driver.session(database=database) as session:
        for query in CONSTRAINTS:
            session.run(query).consume()

        session.run(
            UPSERT_DISEASES,
            rows=DISEASE_NODES,
        ).consume()

        session.run(
            UPSERT_NEEDS,
            rows=CONSULTATION_NEED_NODES,
        ).consume()

        session.run(
            UPSERT_WARNINGS,
            rows=WARNING_NODES,
        ).consume()

        session.run(
            UPSERT_DISEASE_NEEDS,
            rows=DISEASE_NEED_EDGES,
        ).consume()

        session.run(
            UPSERT_DISEASE_WARNINGS,
            rows=DISEASE_WARNING_EDGES,
        ).consume()

    return {
        "disease_nodes": len(DISEASE_NODES),
        "consultation_need_nodes": len(CONSULTATION_NEED_NODES),
        "warning_nodes": len(WARNING_NODES),
        "disease_need_edges": len(DISEASE_NEED_EDGES),
        "disease_warning_edges": len(DISEASE_WARNING_EDGES),
        "total_nodes": (
            len(DISEASE_NODES) + len(CONSULTATION_NEED_NODES) + len(WARNING_NODES)
        ),
        "total_edges": (len(DISEASE_NEED_EDGES) + len(DISEASE_WARNING_EDGES)),
    }


def main():
    try:
        result = upsert_knowledge_graph()

        print("=== Neo4j Knowledge Graph Upsert Completed ===")

        for key, value in result.items():
            print(f"{key}: {value}")

    finally:
        Neo4jClient.close_driver()


